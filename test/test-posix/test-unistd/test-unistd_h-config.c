#include <errno.h>

int
main(void)
{
    size_t i;
    int    fails = 0;

    /* sysconf and confstr know every name, and leave errno alone for them */
    for (i = 0; i < sizeof(sc_names) / sizeof(sc_names[0]); i++) {
        if (sc_names[i].value <= -1000)
            continue;
        /* glibc fails these with EINVAL */
#ifdef __GLIBC__
        if (sc_names[i].value == _SC_SS_REPL_MAX
            || sc_names[i].value == _SC_THREAD_ROBUST_PRIO_INHERIT
            || sc_names[i].value == _SC_THREAD_ROBUST_PRIO_PROTECT)
            continue;
#endif
        errno = 0;
        (void)sysconf(sc_names[i].value);
        if (errno != 0) {
            printf("sysconf(%s): errno %d\n", sc_names[i].name, errno);
            fails++;
        }
    }
    for (i = 0; i < sizeof(cs_names) / sizeof(cs_names[0]); i++) {
        if (cs_names[i].value <= -1000)
            continue;
        errno = 0;
        if (confstr(cs_names[i].value, NULL, 0) == 0 && errno != 0) {
            printf("confstr(%s): errno %d\n", cs_names[i].name, errno);
            fails++;
        }
    }
    if (fails)
        return 1;
    printf("success\n");
    return 0;
}
