"""Support for the claim-all test mode (doc/testing.md).

With TEST_CLAIM_ALL defined, test-flags.h claims every option group and
option at POSIX.1-2024, so the tests of what the library does not claim
run too and should fail. This script supplies the two pieces the build
systems need:

expect   At configure time, preprocess each test with and without
         TEST_CLAIM_ALL. A test whose preprocessed text differs runs
         code the library's real claims leave out, so it is expected to
         fail. Prints one line per such test: its name and the TEST_
         symbols it uses that the library claims below POSIX.1-2024,
         and writes them to a table, followed by the real claims.

build    (meson) At build time, compile and link a test the way the
         build will. Write a C file that includes the test when that
         works, or a stand-in whose main reports the build errors and
         fails when it doesn't, so a test that can't build counts as a
         failed test rather than a broken build.

compile, link
         (CMake) The same, as RULE_LAUNCH_COMPILE and RULE_LAUNCH_LINK
         launchers: run the command, and when it fails, build the
         stand-in in its place.
"""

import concurrent.futures
import json
import os
import re
import subprocess
import sys
import tempfile

CLAIM_ALL = "202405L"


def c_string(text):
    """Quote text as a C string literal."""
    out = []
    for ch in text:
        if ch in '\\"':
            out.append("\\" + ch)
        elif ch == "\n":
            out.append('\\n"\n    "')
        elif ch == "\t" or " " <= ch <= "~":
            out.append(ch)
        elif ch in "\u2018\u2019":
            # The compilers' quotes
            out.append("'")
        else:
            out.append("?")
    return '"' + "".join(out) + '"'


def stub_source(name, log):
    """A test that reports why the real one didn't build, and fails."""
    lines = [l for l in log.splitlines() if "error" in l or "undefined" in l]
    if not lines:
        lines = log.splitlines()
    message = "\n".join(lines[:20]) + "\n"
    return (
        "/* Generated by claim-all.py: %s does not build */\n"
        "#include <stdio.h>\n"
        "\n"
        "int\n"
        "main(void)\n"
        "{\n"
        '    printf("claim-all: %%s does not build\\n%%s", "%s",\n'
        "    %s);\n"
        "    return 1;\n"
        "}\n" % (name, name, c_string(message))
    )


def write_if_changed(path, text):
    try:
        with open(path) as f:
            if f.read() == text:
                return
    except OSError:
        pass
    with open(path, "w") as f:
        f.write(text)


def run(cmd):
    proc = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, errors="replace")
    return proc.returncode, proc.stdout


#
# expect
#


def preprocess(cmd, src, extra):
    rc, out = run(cmd + extra + ["-E", "-P", src])
    if rc != 0:
        return None
    # Line breaks move with the removed text; compare the tokens
    return out.split()


def real_values(cmd, flags_header, symbols):
    """The value of each TEST_ symbol without TEST_CLAIM_ALL."""
    with tempfile.TemporaryDirectory() as tmp:
        src = os.path.join(tmp, "values.c")
        with open(src, "w") as f:
            f.write('#include "%s"\n' % flags_header)
            for s in symbols:
                f.write("claim_all_value_%s %s\n" % (s, s))
        rc, out = run(cmd + ["-E", "-P", src])
    values = {}
    if rc == 0:
        for m in re.finditer(r"claim_all_value_(\w+)\s+(\w+)", out):
            values[m.group(1)] = m.group(2)
    return values


def edition(value):
    try:
        return int(value.rstrip("Ll"), 0)
    except (ValueError, AttributeError):
        return 0


def expect(args):
    """expect FLAGS_HEADER TABLE TEST[::ARG...]... -- COMPILER ARGS..."""
    split = args.index("--")
    flags_header, table = args[0:2]
    tests = args[2:split]
    cmd = args[split + 1 :]

    with open(flags_header) as f:
        symbols = sorted(set(re.findall(r"#define\s+(TEST_\w+)\s+" + CLAIM_ALL, f.read())))
    values = real_values(cmd, flags_header, symbols)
    # Options that are only on or off are claimed when not 0
    below = set(s for s in symbols if not 1 <= edition(values.get(s, "0")) < 199000 and edition(values.get(s, "0")) < edition(CLAIM_ALL))

    def check(entry):
        parts = entry.split("::")
        src, extra = parts[0], parts[1:]
        real = preprocess(cmd, src, extra)
        claim = preprocess(cmd, src, extra + ["-DTEST_CLAIM_ALL"])
        # Only a test the real claims can build can be told apart
        if real is None or real == claim:
            return None
        with open(src, errors="replace") as f:
            used = sorted(below & set(re.findall(r"\bTEST_\w+\b", f.read())))
        return os.path.splitext(os.path.basename(src))[0], used

    lines = []
    with concurrent.futures.ThreadPoolExecutor(max_workers=os.cpu_count() or 4) as pool:
        for result in pool.map(check, tests):
            if result:
                lines.append("%s %s\n" % (result[0], ",".join(result[1]) or "-"))
    # The table, with the values it came from, for looking into results
    with open(table, "w") as f:
        f.write("# Tests expected to fail, and what they use that isn't claimed\n")
        f.writelines(lines)
        f.write("# The claims\n")
        for s in symbols:
            f.write("# %s %s\n" % (s, values.get(s, "?")))
    sys.stdout.writelines(lines)
    return 0


#
# build (meson)
#


def build(args):
    """build NAME SOURCE OUTPUT -- COMPILER ARGS... (SOURCE goes first)"""
    name, source, output = args[0:3]
    cmd = args[args.index("--") + 1 :]
    exe = output + ".exe"
    # Libraries go last, grouped, as meson links them
    libs = [a for a in cmd[1:] if a.endswith(".a") or (a.startswith("-l") and len(a) > 2)]
    args = [a for a in cmd[1:] if a not in libs]
    if libs:
        libs = ["-Wl,--start-group"] + libs + ["-Wl,--end-group"]
    rc, log = run(cmd[:1] + [source] + args + ["-o", exe] + libs)
    try:
        os.unlink(exe)
    except OSError:
        pass
    if rc == 0:
        text = '/* Generated by claim-all.py */\n#include "%s"\n' % os.path.abspath(source)
    else:
        with open(output + ".log", "w") as f:
            f.write(log)
        text = stub_source(name, log)
    write_if_changed(output, text)
    return 0


#
# compile, link (CMake launchers)
#


def option_value(cmd, opt):
    for i, a in enumerate(cmd[:-1]):
        if a == opt:
            return i + 1
    return None


def compile_launcher(args):
    """compile NAME -- COMPILE COMMAND... ('-o OBJ -c SRC')"""
    name = args[0]
    cmd = args[args.index("--") + 1 :]
    rc, log = run(cmd)
    sys.stdout.write(log)
    o = option_value(cmd, "-o")
    c = option_value(cmd, "-c")
    if o is None or c is None or os.path.basename(cmd[c]) != name + ".c":
        return rc
    obj = cmd[o]
    # Keep the command, to build the stand-in if the link fails
    with open(obj + ".claim-all.json", "w") as f:
        json.dump(cmd, f)
    if rc == 0:
        return 0
    return build_stub(name, cmd, obj, log)


def build_stub(name, cmd, obj, log):
    stub = obj + ".claim-all.c"
    with open(stub, "w") as f:
        f.write(stub_source(name, log))
    with open(obj + ".claim-all.log", "w") as f:
        f.write(log)
    cmd = list(cmd)
    cmd[option_value(cmd, "-c")] = stub
    cmd[option_value(cmd, "-o")] = obj
    rc, out = run(cmd)
    sys.stdout.write(out)
    return rc


def link_launcher(args):
    """link NAME -- LINK COMMAND..."""
    name = args[0]
    cmd = args[args.index("--") + 1 :]
    rc, log = run(cmd)
    if rc == 0:
        sys.stdout.write(log)
        return 0
    for a in cmd:
        # CMake names the object test.c.o or test.c.obj
        if os.path.basename(a).startswith(name + ".c.") and os.path.exists(a + ".claim-all.json"):
            with open(a + ".claim-all.json") as f:
                compile_cmd = json.load(f)
            # The stand-in replaces the test's object
            stub_obj = a + ".claim-all.o"
            if build_stub(name, compile_cmd, stub_obj, log) != 0:
                break
            rc, out = run([stub_obj if x == a else x for x in cmd])
            sys.stdout.write(out)
            return rc
    sys.stdout.write(log)
    return rc


def main():
    modes = {"expect": expect, "build": build, "compile": compile_launcher, "link": link_launcher}
    if len(sys.argv) < 2 or sys.argv[1] not in modes:
        print("usage: claim-all.py {%s} ..." % ",".join(modes), file=sys.stderr)
        return 2
    return modes[sys.argv[1]](sys.argv[2:])


if __name__ == "__main__":
    sys.exit(main())
