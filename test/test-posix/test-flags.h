/*
 * What the C library under test provides, for tests to decide what to
 * run.
 *
 * Tests gate only on these TEST_ symbols, never on picolibc's
 * __PICOLIBC_POSIX_<group> and __PICOLIBC_XSI_<group> or on the public
 * _POSIX_<option> and _XOPEN_<option> macros, so that one place says
 * what each library claims:
 *
 *  - TEST_POSIX_<group> and TEST_XSI_<group>, the POSIX option groups
 *    (XBD 2.1.5), which POSIX names but defines no macros for;
 *  - TEST_POSIX_<option> and TEST_XOPEN_<option>, the options.
 *
 * Each is always defined: the edition of POSIX the library meets for
 * it (202405L, 200809L, 200112L), or for the few options that are only
 * on or off the option's value, or 0 when the library lacks it. Tests
 * use plain #if TEST_X, or #if TEST_X >= 202405L for what POSIX.1-2024
 * added, with no defined(), clean under -Wundef.
 *
 *  - picolibc: picolibc's own claims, exactly, as the tests check them;
 *  - glibc: what glibc provides, for the -native tests, which fail when
 *    this over-claims;
 *  - anything else: worked out from _POSIX_VERSION, _XOPEN_UNIX and the
 *    realtime profiles (_POSIX_AEP_REALTIME_*), and the options' values.
 *
 * An option whose value is 0 is there only if sysconf says so at run
 * time. That counts as present only for the CPU-time clocks, whose
 * tests ask sysconf; any other comes out 0. TEST_POSIX_CPUTIME_RUNTIME
 * and TEST_POSIX_THREAD_CPUTIME_RUNTIME are 1 then, so the tests skip
 * what sysconf says is missing. Otherwise (a library claiming the
 * option outright, or TEST_CLAIM_ALL) they are 0 and the tests don't
 * ask: the clocks must be there.
 *
 * Defining TEST_CLAIM_ALL claims everything at POSIX.1-2024, to see
 * that the tests of what the library lacks fail.
 *
 * Include this after the feature-test macros. It includes <unistd.h>.
 */

