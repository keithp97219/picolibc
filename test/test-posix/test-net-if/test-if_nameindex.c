/* if_nameindex lists interfaces that if_nametoindex and if_indextoname agree on */

#define check(condition, message)                      \
    do {                                               \
        if (!(condition)) {                            \
            printf("%s: %s\n", (message), #condition); \
            exit(1);                                   \
        }                                              \
    } while (0)

/* Skips the test when the system has no sockets of this family */
static int
make_socket(int family, int type)
{
    int fd = socket(family, type, 0);

    if (fd < 0 && (errno == EAFNOSUPPORT || errno == EACCES || errno == EPERM)) {
        printf("no sockets of family %d, skipping\n", family);
        exit(77);
    }
    check(fd >= 0, "socket");
    return fd;
}

/* A loopback IPv4 socket address with port 0 */
static struct sockaddr_in
loopback(void)
{
    struct sockaddr_in sin;

    memset(&sin, 0, sizeof(sin));
    sin.sin_family = AF_INET;
    sin.sin_addr.s_addr = htonl(INADDR_LOOPBACK);
    return sin;
}

/* A connected pair of TCP sockets over the loopback interface */
static void
tcp_pair(int *client, int *server)
{
    struct sockaddr_in sin = loopback();
    socklen_t          len = sizeof(sin);
    int                listener = make_socket(AF_INET, SOCK_STREAM);

    check(bind(listener, (struct sockaddr *)&sin, sizeof(sin)) == 0, "bind");
    check(listen(listener, 1) == 0, "listen");
    check(getsockname(listener, (struct sockaddr *)&sin, &len) == 0, "getsockname");
    *client = make_socket(AF_INET, SOCK_STREAM);
    check(connect(*client, (struct sockaddr *)&sin, sizeof(sin)) == 0, "connect");
    *server = accept(listener, NULL, NULL);
    check(*server >= 0, "accept");
    check(close(listener) == 0, "close listener");
}

#include <net/if.h>

int
main(void)
{
    struct if_nameindex *list, *i;
    char                 name[IF_NAMESIZE];

    list = if_nameindex();
    check(list != NULL, "if_nameindex");
    for (i = list; i->if_index; i++) {
        check(if_nametoindex(i->if_name) == i->if_index, "if_nametoindex");
        check(if_indextoname(i->if_index, name) == name && strcmp(name, i->if_name) == 0,
              "if_indextoname");
    }
    check(i->if_name == NULL, "terminator");

    /* if_freenameindex leaves errno alone */
    errno = EDOM;
    if_freenameindex(list);
    check(errno == EDOM, "if_freenameindex errno");

    check(if_nametoindex("no-such-if") == 0, "missing name");
    check(if_indextoname(0x7fffffff, name) == NULL && errno == ENXIO, "missing index");
    check(if_nametoindex("a-name-much-too-long-for-an-interface") == 0, "long name");
    check(if_nametoindex("") == 0, "empty name");
    errno = 0;
    check(if_indextoname(0, name) == NULL && errno == ENXIO, "index zero");
    (void)make_socket;
    (void)tcp_pair;
    printf("success\n");
    return 0;
}

