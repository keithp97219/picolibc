#define _POSIX_C_SOURCE 202405L
/* glibc declares mknod and mknodat only for XSI */
#define _XOPEN_SOURCE 700
#include <dirent.h>
#include <errno.h>
#include <fcntl.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <sys/stat.h>
#include <sys/wait.h>
#include <unistd.h>

/* mknodat makes FIFOs and regular files */

#define check(condition, message)                      \
    do {                                               \
        if (!(condition)) {                            \
            printf("%s: %s\n", (message), #condition); \
            exit(1);                                   \
        }                                              \
    } while (0)

static char dir[] = "tmp-XXXXXX";

int
main(void)
{
    struct stat st;
    int         dfd;

    check(mkdtemp(dir) != NULL, "mkdtemp");
    dfd = open(dir, O_RDONLY | O_DIRECTORY);
    check(dfd >= 0, "open dir");
    check(mknodat(dfd, "fifo", S_IFIFO | 0600, 0) == 0, "mknodat FIFO");
    check(fstatat(dfd, "fifo", &st, 0) == 0 && S_ISFIFO(st.st_mode), "is a FIFO");
    check(mknodat(dfd, "fifo", S_IFIFO | 0600, 0) == -1 && errno == EEXIST, "EEXIST");
    check(unlinkat(dfd, "fifo", 0) == 0, "cleanup");
    check(close(dfd) == 0 && rmdir(dir) == 0, "rmdir");
    printf("success\n");
    return 0;
}
