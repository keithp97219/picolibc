/*
 * Check strtof, strtod and strtold on decimal input that comes very
 * close to a multiple of the binary significand's last place without
 * being on it, relative to the length of the input. These are the
 * strings that a fixed-precision conversion like Ryu's gets wrong
 * when its powers of five aren't precise enough: each one here is
 * misjudged when that precision is a little lower than picolibc uses.
 * Each has at most as many digits as picolibc rounds correctly for its
 * type. mk-strtod-hard.py picked them with the method of
 * mk-ryu-table-128.py.
 */

