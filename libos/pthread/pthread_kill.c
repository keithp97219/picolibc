#define _DEFAULT_SOURCE
#include "local-pthread.h"

#ifdef _PTHREAD_HAVE_SIGNALS

int
pthread_kill(pthread_t thread, int sig)
{
    int tid;
    int ksig;

    ksig = _pthread_signal_to_kernel(sig);
    if (ksig < 0)
        return EINVAL;
    tid = __atomic_load_n(&thread->tid, __ATOMIC_ACQUIRE);
    /* A thread which has exited but not been joined is not an error */
    if (tid == 0)
        return 0;
    return _pthread_tkill(thread, ksig);
}

#else

int
pthread_kill(pthread_t thread, int sig)
{
    (void)thread;
    (void)sig;
    return ENOTSUP;
}

#endif
