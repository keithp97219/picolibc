#define _DEFAULT_SOURCE
#include "local-pthread.h"

int
pthread_detach(pthread_t thread)
{
    int state = __PTHREAD_JOINABLE;

    if (__atomic_compare_exchange_n(&thread->detach_state, &state, __PTHREAD_DETACHED, false,
                                    __ATOMIC_ACQ_REL, __ATOMIC_ACQUIRE))
        return 0;
    if (state == __PTHREAD_DETACHED)
        return EINVAL;

    /* The thread is already exiting as a joinable thread; clean it up now */
    _pthread_wait_exit(thread);
    if (thread->map)
        _pthread_unmap(thread->map, thread->map_size);
    return 0;
}
