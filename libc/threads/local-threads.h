#ifndef _LOCAL_THREADS_H_
#define _LOCAL_THREADS_H_

#define _DEFAULT_SOURCE
#include <threads.h>
#include <errno.h>
#include <pthread.h>

/* Maps a pthread error number to a C11 thread result */
static inline int
__thrd_result(int error)
{
    switch (error) {
    case 0:
        return thrd_success;
    case EBUSY:
        return thrd_busy;
    case ETIMEDOUT:
        return thrd_timedout;
    case ENOMEM:
    case EAGAIN:
        return thrd_nomem;
    default:
        return thrd_error;
    }
}

#endif /* _LOCAL_THREADS_H_ */
