#include <search.h>
#include <stddef.h>

/* The elements start with forward and backward pointers */
struct __qelem {
    struct __qelem *next;
    struct __qelem *prev;
};

void
insque(void *element, void *pred)
{
    struct __qelem *e = element, *p = pred;

    if (!p) {
        /* Start a new list */
        e->next = e->prev = NULL;
        return;
    }
    e->prev = p;
    e->next = p->next;
    if (p->next)
        p->next->prev = e;
    p->next = e;
}
