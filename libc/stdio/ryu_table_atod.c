#include "local-stdio.h"

#if __LDBL_MANT_DIG__ == 106

#include "ryu/generic_128.h"

/*
 * Powers of five for decimal input of double-double in atod_ryu.c:
 * the start of the split tables in ryu_table_128.c, which isn't built
 * for double-double, covering its decimal exponents. See
 * mk-ryu-table-128.py
 */

/* Generated by mk-ryu-table-128.py --atod */

/* 106-bit significand, 39 digit input: needs 250 of 251 bits */

#define POW5_TABLE_SIZE 111
_Static_assert(ATOD_RYU_ERR == 3, "decimal input error");
#define MAX_POW5     308
#define MAX_INV_POW5 362

static const uint64_t ATOD_POW5_SPLIT[3][4] = {
    { 0u,                    0u,                    0u,                    288230376151711744u },
    { 17817920149131506316u, 15177692759949761133u, 12926721561028738632u, 479403658720481108u },
    { 2097081990918526177u,  4231410764026209859u,  7755529794602230522u,  398687798043902701u },
};

static const uint64_t ATOD_POW5_INV_SPLIT[5][4] = {
    { 0u,                    0u,                    0u,                    576460752303423488u },
    { 13953982050075049414u, 3193666284231239482u,  8251261330577453682u,  346583711765101857u },
    { 15370256559224247902u, 18137610286108098863u, 2397905855917597553u,  416750902054990892u },
    { 6425678860505541779u,  1348737806211756938u,  2119334793147527324u,  501123706821403193u },
    { 10318269692440236576u, 8806555200360709755u,  10561029857393938571u, 301289053365129073u },
};

void
__atod_ryu_pow5(const uint32_t i, const bool inv, ryu_limb * const result)
{
    uint32_t base, base2;

    assert(inv ? i <= MAX_INV_POW5 : i <= MAX_POW5);
    if (inv) {
        base = (i + POW5_TABLE_SIZE - 1) / POW5_TABLE_SIZE;
        base2 = base * POW5_TABLE_SIZE;
        generic_mul_pow5_shift(ATOD_POW5_INV_SPLIT[base], 4, base2 - i,
                               generic_pow5bits(base2) - generic_pow5bits(i), ATOD_RYU_ERR, result);
    } else {
        base = i / POW5_TABLE_SIZE;
        base2 = base * POW5_TABLE_SIZE;
        generic_mul_pow5_shift(ATOD_POW5_SPLIT[base], 4, i - base2,
                               generic_pow5bits(i) - generic_pow5bits(base2), 0, result);
    }
}

#endif /* __LDBL_MANT_DIG__ == 106 */
