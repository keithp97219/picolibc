// Returns the number of decimal digits in v, which must be less than 10^10
static int
decimalLength10(const uint32_t v)
{
    int      len = 1;
    uint32_t c = 10;

    if (v >= 1000000000)
        return 10;
    while (c <= v) {
        len++;
        c = (c << 3) + (c << 1);
    }
    return len;
}

// Returns (m * factor) >> shift for 32 < shift < 64
static uint32_t
mulShift32(const uint32_t m, const uint64_t factor, const int32_t shift)
{
    const uint64_t bits0 = (uint64_t)m * (uint32_t)factor;
    const uint64_t bits1 = (uint64_t)m * (uint32_t)(factor >> 32);
    const uint32_t bits0Hi = (uint32_t)(bits0 >> 32);
    uint32_t       bits1Lo = (uint32_t)bits1;
    uint32_t       bits1Hi = (uint32_t)(bits1 >> 32);
    const int32_t  s = shift - 32;

    bits1Lo += bits0Hi;
    bits1Hi += (bits1Lo < bits0Hi);
    return (bits1Hi << (32 - s)) | (bits1Lo >> s);
}

int
__ftoa_engine(uint32_t bits, struct dtoa *dtoa, int max_digits, bool fmode, int max_decimals)
{
    // Decode bits into sign, mantissa, and exponent.
    const bool     ieeeSign = ((bits >> (FLOAT_MANTISSA_BITS + FLOAT_EXPONENT_BITS)) & 1) != 0;
    const uint32_t ieeeMantissa = bits & (((uint32_t)1 << FLOAT_MANTISSA_BITS) - 1);
    const uint32_t ieeeExponent
        = (uint32_t)((bits >> FLOAT_MANTISSA_BITS) & (((uint32_t)1 << FLOAT_EXPONENT_BITS) - 1));

    uint8_t flags = 0;

    if (ieeeSign)
        flags |= DTOA_MINUS;

    if (ieeeExponent == 0 && ieeeMantissa == 0) {
        flags |= DTOA_ZERO;
        dtoa->digits[0] = '0';
        dtoa->flags = flags;
        dtoa->exp = 0;
        return 1;
    }
    if (ieeeExponent == (((uint32_t)1 << FLOAT_EXPONENT_BITS) - 1)) {
        if (ieeeMantissa) {
            flags |= DTOA_NAN;
        } else {
            flags |= DTOA_INF;
        }
        dtoa->flags = flags;
        return 0;
    }

    // Normalize to 2^23 <= m2 < 2^24, the value is m2 * 2^e2
    int32_t  e2;
    uint32_t m2;
    if (ieeeExponent == 0) {
        e2 = 1 - FLOAT_BIAS - FLOAT_MANTISSA_BITS;
        m2 = ieeeMantissa;
        while (!(m2 & ((uint32_t)1 << FLOAT_MANTISSA_BITS))) {
            m2 <<= 1;
            e2--;
        }
    } else {
        e2 = (int32_t)ieeeExponent - FLOAT_BIAS - FLOAT_MANTISSA_BITS;
        m2 = ((uint32_t)1 << FLOAT_MANTISSA_BITS) | ieeeMantissa;
    }

    // Don't generate more digits than the conversion is defined for
    if (max_digits > FTOA_MAX_DIG)
        max_digits = FTOA_MAX_DIG;

    /*
     * e10 = floor(log10(2^(e2 + 23))) - 8, so that 10^8 <= m2 * 2^e2 /
     * 10^e10 < 2 * 10^9. Compute vr2 = floor(2 * m2 * 2^e2 / 10^e10)
     * and whether that is exact; mk-ryu-table-float.py shows that the
     * table values are precise enough for this to be the exact floor.
     * This relies on >> of a negative value rounding toward -infinity.
     */
    int32_t  e10 = (((e2 + FLOAT_MANTISSA_BITS) * 78913) >> 18) - (FTOA_MAX_DIG - 1);
    uint32_t vr2;
    bool     vrIsTrailingZeros;

    if (e10 >= 0) {
        // vr2 = floor(m2 * 2^s / 5^e10), exact iff 5^e10 divides m2
        const int32_t s = e2 + 1 - e10;
        vr2 = mulShift32(m2, FLOAT_POW5_INV[e10], pow5bits(e10) - 1 + FLOAT_POW5_INV_BITCOUNT - s);
        uint32_t m = m2;
        int32_t  q = e10;
        while (q > 0 && m % 5 == 0) {
            m /= 5;
            q--;
        }
        vrIsTrailingZeros = q == 0;
    } else {
        // vr2 = floor(m2 * 5^p / 2^t), exact iff 2^t divides m2
        const int32_t p = -e10;
        const int32_t t = -(e2 + 1 + p);
        uint64_t      pow5;
        if (p <= FLOAT_MAX_EXACT_POW5) {
            int32_t i;
            pow5 = 1;
            for (i = 0; i < p; i++)
                pow5 *= 5;
            pow5 <<= FLOAT_POW5_BITCOUNT - pow5bits(p);
        } else {
            pow5 = FLOAT_POW5[p - FLOAT_MAX_EXACT_POW5 - 1];
        }
        vr2 = mulShift32(m2, pow5, t - (pow5bits(p) - FLOAT_POW5_BITCOUNT));
        vrIsTrailingZeros = t <= 0 || (t < 32 && (m2 & (((uint32_t)1 << t) - 1)) == 0);
    }

    /*
     * vr = floor(m2 * 2^e2 / 10^e10). The low bit of vr2 is the first
     * bit of the remainder: if set, the remainder is at least one half,
     * which works like a removed digit of 5.
     */
    uint32_t vr = vr2 >> 1;
    uint8_t  lastRemovedDigit = (vr2 & 1) ? 5 : 0;
    int      len = decimalLength10(vr);

    /*
     * In fmode, limit the number of digits to those left of the
     * decimal point plus max_decimals. exp is the exponent of the
     * first digit: if negative, there are -exp - 1 zeros past the
     * decimal point before the first digit, otherwise there are exp + 1
     * digits left of the decimal point.
     *
     * When called from fcvt, max_decimals may be less than zero,
     * indicating that we want to round left of the decimal point. In
     * that case, make sure we generate at least one digit.
     */
    int      save_max_digits = max_digits;
    if (fmode) {
        int exp = e10 + len - 1;
        int ndigits = max_decimals + exp + 1;

        if (ndigits < 0 && max_decimals >= 0) {
            // Value is less than half of the last decimal place
            dtoa->exp = -max_decimals - 1;
            dtoa->flags = flags;
            return 0;
        }
        max_digits = min_int(max_digits, max_int(max_decimals < 0, ndigits));
    }

    // Remove digits, remembering the last one and whether the rest were zero
    while (len > max_digits) {
        vrIsTrailingZeros &= lastRemovedDigit == 0;
        lastRemovedDigit = (uint8_t)(vr % 10);
        vr /= 10;
        e10++;
        len--;
    }

    if (vrIsTrailingZeros && lastRemovedDigit == 5 && vr % 2 == 0) {
        // Round even if the exact number is .....50..0.
        lastRemovedDigit = 4;
    }

    if (lastRemovedDigit >= 5) {
        vr++;
        if (len == 0 || decimalLength10(vr) > len) {
            // Carried out of the top digit, giving a power of ten. In
            // fmode, the extra digit is left of the decimal point, so
            // there's room for it unless that would exceed the buffer.
            if (fmode ? len + 1 > save_max_digits : len + 1 > max_digits) {
                vr /= 10;
                e10++;
            } else {
                len++;
            }
        }
    }

    int i;

    for (i = 0; i < len; i++) {
        dtoa->digits[len - i - 1] = (vr % 10) + '0';
        vr /= 10;
    }

    dtoa->exp = e10 + len - 1;
    dtoa->flags = flags;
    return len;
}
