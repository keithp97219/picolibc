/*
 * Float to decimal conversion using only 32-bit values and 32x32->64
 * bit multiplies, generating exactly rounded digits.
 *
 * Like Ryu's f2s, this multiplies the significand by a 64-bit
 * approximation of a power of five and keeps the top bits. Unlike
 * f2s, which needs only enough digits to find the shortest string
 * that round-trips, the decimal exponent is chosen so that the
 * product has 9 or 10 digits plus one more bit, and the multipliers
 * are precise enough that this is the exact floor of the value. That
 * bit and whether the division was exact are enough to round
 * correctly to FTOA_MAX_DIG digits.
 *
 * Powers of five up to 5^27 fit in 64 bits; those are computed rather
 * than stored, leaving 57 table entries (456 bytes).
 */

#define _NEED_IO_FLOAT32

#include "dtoa.h"
#include "ryu/common.h"

#define FLOAT_MANTISSA_BITS 23
#define FLOAT_EXPONENT_BITS 8
#define FLOAT_BIAS          127

/* Generated by mk-ryu-table-float.py */

#define FLOAT_POW5_INV_BITCOUNT 63
