// Returns 5^n for 0 <= n < POW5_TABLE_SIZE in a[0] (low) .. a[3] (high).
static void
pow5_256(uint32_t n, uint64_t * const a)
{
    int j;

    a[0] = 1;
    a[1] = a[2] = a[3] = 0;
    while (n) {
        // 5^27 is the largest power of five that fits in 64 bits
        uint32_t k = n < 27 ? n : 27;
        uint64_t m = 1;
        uint64_t carry = 0;

        n -= k;
        while (k--)
            m *= 5;
        for (j = 0; j < 4; j++) {
            _u128 t = _u128_plus_64(_u128_mul_64(a[j], m), carry);
            a[j] = _u128_lo64(t);
            carry = _u128_hi64(t);
        }
    }
}

// Computes 5^i in the form required by Ryu, and stores it in the given pointer.
void
__generic_computePow5(const uint32_t i, uint64_t * const result)
{
    assert(i <= MAX_POW5);
    const uint32_t         base = i / POW5_TABLE_SIZE;
    const uint32_t         base2 = base * POW5_TABLE_SIZE;
    const uint64_t * const mul = GENERIC_POW5_SPLIT[base];
    if (i == base2) {
        result[0] = mul[0];
        result[1] = mul[1];
        result[2] = mul[2];
        result[3] = mul[3];
    } else {
        const uint32_t offset = i - base2;
        uint64_t       m[4];
        pow5_256(offset, m);
        const uint32_t delta = generic_pow5bits(i) - generic_pow5bits(base2);
        const uint32_t corr = (uint32_t)((POW5_ERRORS[i / 32] >> (2 * (i % 32))) & 3);
        mul_256_256_shift(m, mul, delta, corr, result);
    }
}

// Computes 5^-i in the form required by Ryu, and stores it in the given pointer.
void
__generic_computeInvPow5(const uint32_t i, uint64_t * const result)
{
    assert(i <= MAX_INV_POW5);
    const uint32_t         base = (i + POW5_TABLE_SIZE - 1) / POW5_TABLE_SIZE;
    const uint32_t         base2 = base * POW5_TABLE_SIZE;
    const uint64_t * const mul = GENERIC_POW5_INV_SPLIT[base]; // 1/5^base2
    if (i == base2) {
        result[0] = mul[0] + 1;
        result[1] = mul[1];
        result[2] = mul[2];
        result[3] = mul[3];
    } else {
        const uint32_t offset = base2 - i;
        uint64_t       m[4];
        pow5_256(offset, m); // 5^offset
        const uint32_t delta = generic_pow5bits(base2) - generic_pow5bits(i);
        const uint32_t corr = (uint32_t)((POW5_INV_ERRORS[i / 32] >> (2 * (i % 32))) & 3) + 1;
        mul_256_256_shift(m, mul, delta, corr, result);
    }
}

