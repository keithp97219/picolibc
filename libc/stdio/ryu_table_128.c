/*
 * Tables for the 128-bit Ryu code in ldtoa_ryu.c and for long double
 * decimal input in atod_ryu.c. These follow Ryu's
 * generic_128.h, but store every 111th power of five instead of every
 * 56th; the intermediate values are computed using a power of five
 * which fits in 256 bits instead of 128 bits. That halves the size of
 * the split tables. The 5^0 .. 5^55 table from upstream isn't needed
 * either, pow5_256 computes those values.
 *
 * The values have 251 bits instead of 249, and the tables extend to
 * the powers needed for normalized subnormal values; see
 * mk-ryu-table-128.py
 *
 * The split tables hold 5^(111 i) and 5^-(111 i) for every i needed
 * by a 15-bit binary exponent, the error tables correct the low bits
 * of the values computed from them. They also cover the decimal
 * exponents of long double input.
 */

